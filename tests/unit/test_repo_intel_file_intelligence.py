"""Unit tests for QB-079's `file_intelligence.json` build-time helpers in
`quor/pipeline/repo_profile/intel.py`: `_primary_symbol_names()`,
`_classify_kind()`, and `_build_file_intelligence()`.

Also includes a parity test asserting `_build_file_intelligence()` and
`explorer.py::file_summary()` agree on `importance`/import counts for the
same synthetic repo — proving the `dashboard.importance_tiers()` extraction
(shared by both QB-078's `quor explore` and QB-079's build-time cache)
didn't silently diverge the two call sites.
"""

from __future__ import annotations

from collections import Counter
from pathlib import Path

from quor.pipeline.ast_summarize.symbol_model import Symbol
from quor.pipeline.repo_profile.explorer import ExplorerCache, file_summary
from quor.pipeline.repo_profile.graph import FileFacts
from quor.pipeline.repo_profile.graph_model import Edge, RepoDependencyGraph
from quor.pipeline.repo_profile.intel import (
    _build_file_intelligence,
    _classify_kind,
    _primary_symbol_names,
)
from quor.pipeline.repo_profile.intel_model import FileFingerprint, RepoIntelState
from quor.pipeline.repo_profile.model import DetectedItem, RepoProfile, RepoStatistics
from quor.pipeline.repo_profile.symbols_model import FileSymbols
from quor.pipeline.repo_profile.walk import WalkResult


def _profile(root: Path, *, configuration_files: list[DetectedItem] | None = None, lockfiles: list[str] | None = None) -> RepoProfile:
    return RepoProfile(
        root=root.as_posix(),
        configuration_files=configuration_files or [],
        lockfiles=lockfiles or [],
        statistics=RepoStatistics(total_files=0, total_directories=0, primary_language=None, git_commit_count=None),
    )


class TestPrimarySymbolNames:
    def test_none_input_returns_empty(self) -> None:
        assert _primary_symbol_names(None) == []

    def test_public_top_level_only_methods_excluded(self) -> None:
        fs = FileSymbols(
            path="a.py",
            language="python",
            symbols=[
                Symbol(name="Foo", kind="class", line=1, is_public=True),
                Symbol(name="_private", kind="function", line=5, is_public=False),
                Symbol(name="method", kind="method", line=10, is_public=True),
                Symbol(name="bar", kind="function", line=15, is_public=True),
            ],
        )
        assert _primary_symbol_names(fs) == ["Foo", "bar"]

    def test_declaration_line_order(self) -> None:
        fs = FileSymbols(
            path="a.py",
            language="python",
            symbols=[
                Symbol(name="second", kind="function", line=20, is_public=True),
                Symbol(name="first", kind="function", line=5, is_public=True),
            ],
        )
        assert _primary_symbol_names(fs) == ["first", "second"]

    def test_deduplicates_by_name(self) -> None:
        fs = FileSymbols(
            path="a.py",
            language="python",
            symbols=[
                Symbol(name="overload", kind="function", line=1, is_public=True),
                Symbol(name="overload", kind="function", line=5, is_public=True),
            ],
        )
        assert _primary_symbol_names(fs) == ["overload"]

    def test_capped_at_five(self) -> None:
        fs = FileSymbols(
            path="a.py",
            language="python",
            symbols=[Symbol(name=f"f{i}", kind="function", line=i, is_public=True) for i in range(10)],
        )
        assert _primary_symbol_names(fs) == ["f0", "f1", "f2", "f3", "f4"]


